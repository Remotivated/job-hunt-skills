#!/usr/bin/env node
// Rebuilds the notices shipped beside scripts/vendor/export-deps.mjs.
// Facts come only from the locked install and pdfmake's checked npm artifact.

import {
  existsSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const modules = join(root, "node_modules");
const output = join(root, "scripts/vendor/LICENSES.md");
const pdfmakeMap = JSON.parse(
  readFileSync(join(modules, "pdfmake/build/pdfmake.js.map"), "utf8"),
);

const directBundlePackages = [
  "docx",
  "entities",
  "linkify-it",
  "markdown-it",
  "mdurl",
  "pdfmake",
  "punycode.js",
  "uc.micro",
];

function packageNameFromSource(source) {
  const match = source.match(
    /node_modules\/(?:\.pnpm\/[^/]+\/node_modules\/)?((?:@[^/]+\/)?[^/]+)/,
  );
  return match?.[1] ?? null;
}

const embeddedPackages = [...new Set(
  pdfmakeMap.sources.map(packageNameFromSource).filter(Boolean),
)].sort();

function legalComments(source) {
  return [...source.matchAll(/\/\*[\s\S]*?\*\//g)]
    .map((match) => match[0].trim())
    .filter((comment) =>
      /copyright|@license|licensed under|\blicen[cs]e\b/i.test(comment),
    );
}

const embeddedNotices = [...new Set(
  pdfmakeMap.sourcesContent.flatMap((source) => legalComments(source ?? "")),
)].sort();

function localPackageRecord(name) {
  const dir = join(modules, ...name.split("/"));
  const packagePath = join(dir, "package.json");
  if (!existsSync(packagePath)) return null;
  const pkg = JSON.parse(readFileSync(packagePath, "utf8"));
  const licenseFiles = readdirSync(dir)
    .filter((file) => /^(licen[cs]e|copying|notice)(\.|$)/i.test(file))
    .sort();
  return {
    name,
    version: pkg.version ?? "unknown",
    declaredLicense: pkg.license ?? "not declared",
    licenses: licenseFiles.map((file) => ({
      file,
      text: readFileSync(join(dir, file), "utf8").trim(),
    })),
  };
}

const representedPackages = [...new Set([
  ...directBundlePackages,
  ...embeddedPackages,
])].sort();
const localRecords = representedPackages
  .map(localPackageRecord)
  .filter(Boolean);

const lines = [
  "# Vendor bundle licenses and notices",
  "",
  "<!-- Generated by scripts/generate-vendor-notices.mjs. Do not edit by hand. -->",
  "",
  "`export-deps.mjs` is built from the locked npm install. It contains direct",
  "esbuild inputs plus the already-bundled `pdfmake/build/pdfmake.js` artifact.",
  "This file ships beside the bundle; `export-deps.mjs.LEGAL.txt` preserves",
  "esbuild-recognized legal comments in their build output as an additional",
  "machine-generated record.",
  "",
  "The represented license families include MIT, Apache License, Version 2.0,",
  "BSD 2-Clause, BSD 3-Clause, ISC, 0BSD, Zlib, BlueOak-1.0.0, and the",
  "MIT option of `(MIT OR GPL-3.0-or-later)` where applicable. In particular,",
  "pdfmake's prebuilt artifact contains Google Brotli decompressor portions",
  "copyright Google Inc. and licensed under Apache-2.0; it is not all MIT code.",
  "",
  "## Direct bundle packages",
  "",
  ...directBundlePackages.map((name) => `- \`${name}\``),
  "",
  "## Packages named by the pdfmake source map",
  "",
  ...embeddedPackages.map((name) => `- \`${name}\``),
  "",
  "## Installed package license files",
  "",
];

for (const record of localRecords) {
  lines.push(
    `### ${record.name} ${record.version} — ${record.declaredLicense}`,
    "",
  );
  if (!record.licenses.length) {
    lines.push("No top-level license file was present in the locked package.", "");
    continue;
  }
  for (const license of record.licenses) {
    lines.push(`Source: \`${record.name}/${license.file}\``, "", "```text");
    lines.push(license.text, "```", "");
  }
}

lines.push("## Legal notices embedded in pdfmake's prebuilt artifact", "");
for (const notice of embeddedNotices) {
  lines.push("```text", notice, "```", "");
}

writeFileSync(output, `${lines.join("\n").trimEnd()}\n`, "utf8");
console.log(`Wrote ${output}`);
