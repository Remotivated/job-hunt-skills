#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pluginRoot = join(root, "plugins/job-hunt-skills");
const vendorDir = join(pluginRoot, "scripts/vendor");

// Recorded license paths are relative to the plugin root, except packages
// read from the repository's node_modules/.
const licensePath = (relativePath) =>
  join(relativePath.startsWith("node_modules/") ? root : pluginRoot, relativePath);
const output = join(vendorDir, "LICENSES.md");

function normalizeGeneratedText(text) {
  return text
    .replaceAll("\r\n", "\n")
    .replaceAll("\r", "\n")
    .split("\n")
    .map((line) => line.trimEnd())
    .join("\n")
    .trimEnd() + "\n";
}

if (process.argv.includes("--normalize-legal")) {
  const legalPath = join(vendorDir, "LEGAL.txt");
  writeFileSync(
    legalPath,
    normalizeGeneratedText(readFileSync(legalPath, "utf8")),
    "utf8",
  );
  console.log(`Normalized ${legalPath}`);
  process.exit(0);
}

const inventory = JSON.parse(
  readFileSync(join(vendorDir, "vendor-inputs.json"), "utf8"),
);
if (inventory.unresolved.length) {
  throw new Error(
    `Refusing to render notices with unresolved records: ${inventory.unresolved.join(", ")}`,
  );
}

const lines = [
  "# Vendored module licenses and notices",
  "",
  "<!-- Generated by scripts/render-vendor-notices.mjs. Do not edit by hand. -->",
  "",
  "`export-deps.mjs` and `modules/` are readable modules generated from the repository lockfile.",
  "Fontkit uses its source modules; its small Unicode shaping tables are embedded as text.",
  "WOFF2/Brotli decoding and SVG rendering are explicitly unsupported; the exporter embeds TrueType fonts.",
  "Word documents use the plugin's own OOXML writer and Node's built-in compression.",
  "",
  "**Zero unresolved build-input packages: yes.**",
  "",
  "`LEGAL.txt` preserves upstream legal comments from the shipped modules.",
  "`vendor-inputs.json` records every input, output module, package and bundled asset.",
  "",
  "## Esbuild package inputs",
  "",
];

for (const record of inventory.packages) {
  lines.push(
    `- **${record.name} ${record.version}** — ${record.declaredLicense}; ` +
      `license: ${record.licenseFiles.map((path) => `\`${path}\``).join(", ")}`,
  );
}

lines.push("", "## Components adapted inside source packages", "");
for (const record of inventory.embedded) {
  lines.push(
    `### ${record.name} — ${record.version}`,
    "",
    `Declared license: ${record.declaredLicense}`,
    "",
    `Evidence: ${record.notice}.`,
    "",
    `License text source: ${record.licenseTextSource}.`,
    "",
  );
}

const assets = inventory.assets ?? [];
if (assets.length) {
  lines.push("", "## Bundled assets", "");
  for (const record of assets) {
    lines.push(
      `### ${record.name} — ${record.version}`,
      "",
      `Declared license: ${record.declaredLicense}`,
      "",
      `Evidence: ${record.notice}.`,
      "",
      `License text source: ${record.licenseTextSource}.`,
      "",
    );
  }
}

const licensePaths = [...new Set(
  [...inventory.packages, ...inventory.embedded, ...assets]
    .flatMap((record) => record.licenseFiles),
)].sort();

// A package without a LICENSE file declares its license in a README section.
// Keep only that section: the rest of a README is API documentation (with
// remote images and example code) that does not belong in a notices file.
function licenseSection(readme, relativePath) {
  const lines = readme.replaceAll("\r\n", "\n").split("\n");
  const start = lines.findIndex((line) => /^#{1,4}\s+licen[cs]e\b/i.test(line));
  if (start === -1) throw new Error(`No License section in ${relativePath}`);
  const level = lines[start].match(/^#+/)[0].length;
  let end = lines.findIndex((line, i) => i > start && /^#+\s/.test(line)
    && line.match(/^#+/)[0].length <= level);
  if (end === -1) end = lines.length;
  return lines.slice(start, end).join("\n").trim();
}

lines.push("## Complete license texts", "");
for (const relativePath of licensePaths) {
  const text = readFileSync(licensePath(relativePath), "utf8");
  const isReadme = /(^|\/)readme(?:[.\-_]|$)/i.test(relativePath);
  lines.push(
    isReadme ? `### ${relativePath} (License section)` : `### ${relativePath}`,
    "",
    "```text",
    isReadme ? licenseSection(text, relativePath) : text.trim(),
    "```",
    "",
  );
}

writeFileSync(output, normalizeGeneratedText(lines.join("\n")), "utf8");
console.log(`Wrote ${output}`);
