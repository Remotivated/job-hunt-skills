#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const vendorDir = join(root, "scripts/vendor");
const output = join(vendorDir, "LICENSES.md");

function normalizeGeneratedText(text) {
  return text
    .replaceAll("\r\n", "\n")
    .replaceAll("\r", "\n")
    .split("\n")
    .map((line) => line.trimEnd())
    .join("\n")
    .trimEnd() + "\n";
}

if (process.argv.includes("--normalize-legal")) {
  const legalPath = join(vendorDir, "export-deps.mjs.LEGAL.txt");
  writeFileSync(
    legalPath,
    normalizeGeneratedText(readFileSync(legalPath, "utf8")),
    "utf8",
  );
  console.log(`Normalized ${legalPath}`);
  process.exit(0);
}

const inventory = JSON.parse(
  readFileSync(join(vendorDir, "vendor-inputs.json"), "utf8"),
);
if (inventory.unresolved.length) {
  throw new Error(
    `Refusing to render notices with unresolved records: ${inventory.unresolved.join(", ")}`,
  );
}

const lines = [
  "# Vendor bundle licenses and notices",
  "",
  "<!-- Generated by scripts/render-vendor-notices.mjs. Do not edit by hand. -->",
  "",
  "`export-deps.mjs` is built only from packages in the repository lockfile.",
  "The build imports pdfmake's source/server entry instead of its opaque",
  "prebuilt browser artifact, so every pdfmake dependency is an exact esbuild",
  "input with a locally checked package version and license file.",
  "",
  "The inventory also expands docx's exact locked dependency closure because",
  "docx publishes a prebuilt module. Three browser shims identified by docx's",
  "preserved legal comments have explicit pinned notices in",
  "`scripts/vendor/embedded-docx-notices.md`.",
  "",
  "**Zero unresolved build-input packages: yes.**",
  "",
  "`export-deps.mjs.LEGAL.txt` is the normalized esbuild legal-comment output.",
  "`vendor-inputs.json` is the machine-readable zero-omission inventory.",
  "",
  "## Esbuild package inputs",
  "",
];

for (const record of inventory.packages) {
  lines.push(
    `- **${record.name} ${record.version}** — ${record.declaredLicense}; ` +
      `license: ${record.licenseFiles.map((path) => `\`${path}\``).join(", ")}`,
  );
}

lines.push("", "## Components embedded by docx", "");
for (const record of inventory.embedded) {
  lines.push(
    `### ${record.name} ${record.version}`,
    "",
    `Declared license: ${record.declaredLicense}`,
    "",
    `Evidence: ${record.notice}.`,
    "",
    `License text source: ${record.licenseTextSource}.`,
    "",
  );
}

const assets = inventory.assets ?? [];
if (assets.length) {
  lines.push("", "## Bundled assets", "");
  for (const record of assets) {
    lines.push(
      `### ${record.name} — ${record.version}`,
      "",
      `Declared license: ${record.declaredLicense}`,
      "",
      `Evidence: ${record.notice}.`,
      "",
      `License text source: ${record.licenseTextSource}.`,
      "",
    );
  }
}

const licensePaths = [...new Set(
  [...inventory.packages, ...inventory.embedded, ...assets]
    .flatMap((record) => record.licenseFiles),
)].sort();

lines.push("## Complete license texts", "");
for (const relativePath of licensePaths) {
  lines.push(
    `### ${relativePath}`,
    "",
    "```text",
    readFileSync(join(root, relativePath), "utf8").trim(),
    "```",
    "",
  );
}

writeFileSync(output, normalizeGeneratedText(lines.join("\n")), "utf8");
console.log(`Wrote ${output}`);
